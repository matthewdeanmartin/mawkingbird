#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const sources = [
  ['mastodon.social', '116777306758391615'],
  ['fosstodon.org', '116855054431403069'],
  ['cyberplace.social', '116834282425494228'],
  ['fosstodon.org', '116768884064559349'],
  ['fosstodon.org', '116776403249838997'],
  ['mastodon.social', '116533503334952204'],
  ['mastodon.social', '116540107831540575'],
  ['mastodon.me.uk', '116924486223172384'],
  ['mastodon.social', '116784146949292427'],
  ['fosstodon.org', '116854987292715462'],
  ['mastodon.social', '116843436442889237'],
];

function snapshot(account, host) {
  return {
    id: account.id,
    username: account.username,
    acct: account.acct.includes('@') ? account.acct : `${account.username}@${host}`,
    displayName: account.display_name,
    note: account.note,
    url: account.url,
    avatar: account.avatar_static || account.avatar,
    followersCount: account.followers_count,
    followingCount: account.following_count,
    statusesCount: account.statuses_count,
    bot: account.bot,
    locked: account.locked,
  };
}

const kits = await Promise.all(
  sources.map(async ([host, id]) => {
    const response = await fetch(`https://${host}/api/v1/collections/${id}`);
    if (!response.ok) {
      throw new Error(`${host} collection ${id}: HTTP ${response.status}`);
    }
    const { collection, accounts } = await response.json();
    const byId = new Map(accounts.map((account) => [account.id, account]));
    const curator = byId.get(collection.account_id);
    if (!curator) {
      throw new Error(`${host} collection ${id}: curator account missing`);
    }
    const members = collection.items.map((item) => byId.get(item.account_id)).filter(Boolean);
    if (members.length !== collection.item_count) {
      throw new Error(
        `${host} collection ${id}: expected ${collection.item_count} members, received ${members.length}`,
      );
    }
    return {
      id: collection.id,
      title: collection.name,
      description: collection.description,
      curatorName: curator.display_name || curator.username,
      curatorHandle: snapshot(curator, host).acct,
      itemCount: collection.item_count,
      url: collection.url,
      curator: snapshot(curator, host),
      accounts: members.map((account) => snapshot(account, host)),
    };
  }),
);

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'app', 'starter-kits.ts');
writeFileSync(
  target,
  `// Generated by ui/scripts/update-starter-kits.mjs — do not hand-edit.
import { Account, CollectionWithAccounts } from './models';

interface ShippedAccountSnapshot {
  id: string;
  username: string;
  acct: string;
  displayName: string;
  note: string;
  url: string;
  avatar: string;
  followersCount: number;
  followingCount: number;
  statusesCount: number;
  bot: boolean;
  locked: boolean;
}

export interface ShippedStarterKit {
  id: string;
  title: string;
  description: string;
  curatorName: string;
  curatorHandle: string;
  itemCount: number;
  url: string;
  curator: Account;
  accounts: readonly Account[];
}

function shippedAccount(snapshot: ShippedAccountSnapshot): Account {
  return {
    id: snapshot.id,
    username: snapshot.username,
    acct: snapshot.acct,
    display_name: snapshot.displayName,
    note: snapshot.note,
    url: snapshot.url,
    avatar: snapshot.avatar,
    avatar_static: snapshot.avatar,
    header: '',
    header_static: '',
    followers_count: snapshot.followersCount,
    following_count: snapshot.followingCount,
    statuses_count: snapshot.statusesCount,
    bot: snapshot.bot,
    locked: snapshot.locked,
    fields: [],
  };
}

const snapshots = ${JSON.stringify(kits, null, 2)};

export const SHIPPED_STARTER_KITS: readonly ShippedStarterKit[] = snapshots.map((kit) => ({
  ...kit,
  curator: shippedAccount(kit.curator),
  accounts: kit.accounts.map(shippedAccount),
}));

export function shippedStarterKit(id: string): ShippedStarterKit | null {
  return SHIPPED_STARTER_KITS.find((kit) => kit.id === id) ?? null;
}

export function shippedStarterKitCollection(kit: ShippedStarterKit): CollectionWithAccounts {
  const timestamp = '1970-01-01T00:00:00.000Z';
  return {
    collection: {
      id: kit.id,
      account_id: kit.curator.id,
      name: kit.title,
      description: kit.description,
      discoverable: true,
      sensitive: false,
      local: false,
      item_count: kit.accounts.length,
      items: kit.accounts.map((account, index) => ({
        id: \`shipped:\${kit.id}:\${index}\`,
        account_id: account.id,
        state: 'accepted',
        created_at: timestamp,
      })),
      created_at: timestamp,
      updated_at: timestamp,
      uri: kit.url,
      url: kit.url,
    },
    accounts: [kit.curator, ...kit.accounts],
  };
}
`,
);

console.log(
  `Updated ${target} with ${kits.length} kits and ${kits.reduce((sum, kit) => sum + kit.accounts.length, 0)} members.`,
);
