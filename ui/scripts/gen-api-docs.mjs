#!/usr/bin/env node
/**
 * Generate `ui/src/app/observability/api-docs.generated.ts` from the checked-in
 * OpenAPI schema at `mastodon-openapi/dist/schema.json`.
 *
 * Why: the Observability page lists endpoints as bare templates
 * (`GET /api/v1/accounts/:id/statuses`), which tells you *that* something was
 * called but nothing about what it does. The schema already carries, per
 * operation, an `externalDocs.url` pointing at the exact anchor on
 * docs.joinmastodon.org (`/methods/accounts/#statuses`) plus a one-line
 * `summary` — so the table can link straight to the documentation for that call
 * and explain it in a tooltip, with no hand-maintained mapping to drift.
 *
 * The output is committed. This does not run as part of the build: the UI must
 * stay buildable on its own, without the sibling `mastodon-openapi` checkout,
 * and the schema changes about as often as Mastodon ships an API — so the
 * regeneration diff is something you look at deliberately, not build noise.
 *
 * Run with: npm run gen:api-docs
 *
 * ## Encoding
 *
 * Every URL is `https://docs.joinmastodon.org/methods/{section}/#{anchor}`, so
 * only `section` and `anchor` are stored and the page reassembles them. Path
 * templates are rewritten from OpenAPI's `{id}` into the `:id` form that
 * `normalizeEndpoint()` produces, so lookups compare like with like.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SCHEMA = process.env.MASTODON_OPENAPI_SCHEMA ?? join(HERE, '..', '..', '..', 'mastodon_mock', 'mastodon-openapi', 'dist', 'schema.json');
const TARGET = join(HERE, '..', 'src', 'app', 'observability', 'api-docs.generated.ts');
const DOCS_PREFIX = 'https://docs.joinmastodon.org/methods/';
const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'];

/** OpenAPI `{account_id}` → the `:id` placeholder normalizeEndpoint() emits. */
function toTemplate(path) {
  return path
    .split('/')
    .map((seg) => (seg.startsWith('{') && seg.endsWith('}') ? ':id' : seg))
    .join('/');
}

const schema = JSON.parse(readFileSync(SCHEMA, 'utf8'));

/** [method, template, section, anchor, summary] — one row per operation. */
const rows = [];
/** First path segment after the version → its docs section, for the fallback. */
const sections = new Map();
let skipped = 0;

for (const [path, item] of Object.entries(schema.paths ?? {})) {
  for (const method of HTTP_METHODS) {
    const op = item[method];
    if (!op) {
      continue;
    }
    const url = op.externalDocs?.url;
    if (typeof url !== 'string' || !url.startsWith(DOCS_PREFIX)) {
      skipped++;
      continue;
    }
    const [path_, anchor = ''] = url.slice(DOCS_PREFIX.length).split('#');
    const section = path_.replace(/\/$/, '');
    const template = toTemplate(path);
    rows.push([method.toUpperCase(), template, section, anchor, op.summary ?? '']);

    // Fallback key: the family segment ("accounts" in /api/v1/accounts/:id).
    // Recorded per family; ties are broken by first-seen, which is fine because
    // a family maps to one section in practice.
    const family = familyOf(template);
    if (family && !sections.has(family)) {
      sections.set(family, section);
    }
  }
}

/**
 * The segment that identifies which docs section a path belongs to: the one
 * after `/api/v{n}/`, or the first real segment for the unversioned paths
 * (`/oauth/token`, `/health`).
 *
 * Returns null for anything that isn't a usable family — a leading `:id`
 * (`/api/v1/{account_id}/collections`) or a one-off like `/api/oembed`, where
 * the family segment would be a placeholder or the literal "api".
 */
function familyOf(template) {
  const segs = template.split('/').filter(Boolean);
  const family = segs[0] === 'api' && /^v\d+/.test(segs[1] ?? '') ? segs[2] : segs[0];
  if (!family || family === ':id' || family === 'api') {
    return null;
  }
  return family;
}

rows.sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));
const sectionRows = [...sections.entries()].sort((a, b) => a[0].localeCompare(b[0]));

const body = `// GENERATED by ui/scripts/gen-api-docs.mjs from mastodon-openapi/dist/schema.json.
// Do not edit by hand; run \`npm run gen:api-docs\` instead.
// ${rows.length} operations, ${sectionRows.length} sections.

/** One documented operation: method, path template, docs section + anchor, summary. */
export type DocRow = readonly [
  method: string,
  template: string,
  section: string,
  anchor: string,
  summary: string,
];

export const DOC_ROWS: readonly DocRow[] = [
${rows.map((r) => `  [${r.map((v) => JSON.stringify(v)).join(', ')}],`).join('\n')}
];

/**
 * Path family (the segment after \`/api/v{n}/\`) → docs section, used to link to
 * the general area when no operation matches exactly.
 */
export const DOC_SECTIONS: Readonly<Record<string, string>> = {
${sectionRows.map(([family, section]) => `  ${JSON.stringify(family)}: ${JSON.stringify(section)},`).join('\n')}
};
`;

writeFileSync(TARGET, body);
console.log(
  `Wrote ${TARGET}: ${rows.length} operations, ${sectionRows.length} sections` +
    (skipped ? `, ${skipped} skipped (no externalDocs)` : ''),
);
