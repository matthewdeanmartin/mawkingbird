#!/usr/bin/env node
// Offline reconciliation of independent starter content and interface locales.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ui = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const reportPath = join(ui, 'docs/starter-locale-coverage.md');
// Norwegian catalogue tags and UI negotiation use different equivalent codes.
const identity = (code) => (code === 'no' ? 'nb' : code);
const placeholders = (text) =>
  [...text.matchAll(/{{\s*(\w+)\s*}}/g)]
    .map((match) => match[1])
    .sort()
    .join(',');

export function reconcileLocales({ catalog, production, inProgress, dictionaries, controls }) {
  const shipped = [...production, ...inProgress];
  const packLanguages = [...new Set(catalog.packs.map((pack) => pack.lang))].sort();
  const hasPacks = (locale) => packLanguages.some((lang) => identity(lang) === identity(locale));
  const hasDictionary = (locale) => dictionaries.includes(locale);
  const hasUi = (lang) =>
    shipped.some((locale) => identity(locale) === identity(lang) && hasDictionary(locale));
  const missingCopy = [];
  const missingControls = [];
  for (const pack of catalog.packs) {
    for (const field of ['title', 'blurb']) {
      if (!pack[field]?.[pack.lang]?.trim())
        missingCopy.push(`${pack.lang}/${pack.slug}: ${field}`);
    }
  }
  for (const lang of packLanguages) {
    for (const [key, english] of Object.entries(controls.en)) {
      const text = controls[lang]?.[key];
      if (!text?.trim() || placeholders(text) !== placeholders(english)) {
        missingControls.push(`${lang}: ${key}`);
      }
    }
  }
  return {
    generatedAt: catalog.generatedAt,
    packs: catalog.packs.length,
    rows: [...new Set([...packLanguages, ...shipped.filter((locale) => !hasPacks(locale))])]
      .sort()
      .map((lang) => ({
        language: lang,
        packs: catalog.packs.filter((pack) => identity(pack.lang) === identity(lang)).length,
        ui: production.some((l) => identity(l) === identity(lang) && hasDictionary(l))
          ? 'Production'
          : inProgress.some((l) => identity(l) === identity(lang) && hasDictionary(l))
            ? 'In progress (test/canary)'
            : 'Missing',
      })),
    startersWithoutUi: packLanguages.filter((lang) => !hasUi(lang)),
    productionWithoutStarters: production.filter((lang) => !hasPacks(lang)),
    inProgressWithoutStarters: inProgress.filter((lang) => !hasPacks(lang)),
    missingDictionaries: shipped.filter((lang) => !hasDictionary(lang)),
    unregisteredDictionaries: dictionaries.filter((lang) => !shipped.includes(lang)),
    missingCopy,
    missingControls,
  };
}

export function renderReport(report) {
  const list = (items) => (items.length ? items.map((item) => `\`${item}\``).join(', ') : 'None');
  return `# Starter and UI locale coverage

Generated by \`npm run starter-locales:report -- --write\`. Do not edit by hand.
Source: the bundled catalogue (${report.generatedAt}), locale registration,
public UI dictionaries, and the independent starter control dictionary.

${report.packs} packs across ${report.rows.filter((row) => row.packs).length} catalogue languages.

| Language | Packs | App-wide UI |
| --- | ---: | --- |
${report.rows.map((row) => `| ${row.language} | ${row.packs} | ${row.ui} |`).join('\n')}

- Starter languages without a registered UI dictionary: ${list(report.startersWithoutUi)}.
- Production UI locales without starters: ${list(report.productionWithoutStarters)}.
- In-progress UI locales without starters: ${list(report.inProgressWithoutStarters)}.
- Registered locales missing their dictionary file: ${list(report.missingDictionaries)}.
- Dictionary files without locale registration: ${list(report.unregisteredDictionaries)}.
- Packs missing their content-language title or description: ${list(report.missingCopy)}.
- Missing starter controls or mismatched placeholders: ${list(report.missingControls)}.

UI status means registration and dictionary presence, not 100% translated keys;
run \`make i18n\` for global translation coverage. Starter-only translations do not
enable a locale in the app picker. In-progress UI locales appear only on test/canary.
\`zh\` and \`zh-Hant\` are distinct; \`no\` and \`nb\` match as Norwegian aliases.
No pack is invented or relabelled to fill a gap: membership comes from the
source catalogue's consent and language checks.
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const read = (file) => JSON.parse(readFileSync(join(ui, file), 'utf8'));
  const localeSource = readFileSync(join(ui, 'src/app/i18n/locale.ts'), 'utf8');
  const locales = (name) => {
    const array = localeSource.match(
      new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\] as const`),
    );
    if (!array) throw new Error(`Cannot read ${name} from locale.ts`);
    return [...array[1].matchAll(/'([^']+)'/g)].map((match) => match[1]);
  };
  const report = reconcileLocales({
    catalog: read('src/app/starter-catalog.generated.json'),
    production: locales('PRODUCTION_LOCALES'),
    inProgress: locales('IN_PROGRESS_LOCALES'),
    dictionaries: readdirSync(join(ui, 'public/i18n'))
      .filter((f) => f.endsWith('.json'))
      .map((f) => f.slice(0, -5)),
    controls: read('src/app/starter-pack-ui.json'),
  });
  const rendered = renderReport(report);
  const args = process.argv.slice(2);
  if (args.includes('--write')) writeFileSync(reportPath, rendered);
  console.log(args.includes('--json') ? JSON.stringify(report, null, 2) : rendered);
  if (args.includes('--check')) {
    if (readFileSync(reportPath, 'utf8').replaceAll('\r\n', '\n') !== rendered) {
      console.error('Locale report is stale. Run npm run starter-locales:report -- --write.');
      process.exitCode = 1;
    }
    if (
      report.missingCopy.length ||
      report.missingControls.length ||
      report.missingDictionaries.length
    ) {
      console.error('Starter translations or registered UI dictionaries are incomplete.');
      process.exitCode = 1;
    }
  }
}
